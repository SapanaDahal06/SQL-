CREATE TABLE EMPLOYEE_PRACTICE (
    EMP_ID INT PRIMARY KEY,
    EMP_NAME VARCHAR(50),
    DEPARTMENT VARCHAR(50),
    SALARY INT,
    BONUS INT
);

